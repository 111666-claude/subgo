// ASSMetadata holds the parts of an ASS/SSA script that are not dialogue events.
// It is preserved so that a sliced script keeps its script info, styles and
// attached fonts.
type ASSMetadata struct {
	// Header is the raw text preceding the first section, usually a BOM.
	Header string
	// Sections holds every non-events section in file order.
	Sections []ASSSection
	// EventFormat is the field list of the events [Format] line, as written.
	EventFormat string
	// Styles lists the style names declared by the script, in file order.
	Styles []string
}

// ASSSection is a raw ASS/SSA section such as [Script Info] or [V4+ Styles].
type ASSSection struct {
	Name  string
	Lines []string
}

// ASSEvent holds the fields of a single ASS/SSA Dialogue line.
type ASSEvent struct {
	// Fields holds every dialogue field, including Start and End, in format order.
	Fields []ASSField
}

// ASSField is one field of an ASS/SSA Dialogue line.
type ASSField struct {
	Name  string
	Value string
}

// Value returns the value of the named dialogue field, case-insensitively.
func (e *ASSEvent) Value(name string) (string, bool) {
	if e == nil {
		return "", false
	}
	for _, f := range e.Fields {
		if strings.EqualFold(f.Name, name) {
			return f.Value, true
		}
	}
	return "", false
}

// Style returns the style referenced by the event, or "Default" when absent.
func (e *ASSEvent) Style() string {
	if style, ok := e.Value("style"); ok && style != "" {
		return style
	}
	return defaultASSStyle
}

// WithField returns a copy of the event with the named field replaced.
func (e *ASSEvent) WithField(name, value string) *ASSEvent {
	if e == nil {
		return nil
	}
	out := &ASSEvent{Fields: make([]ASSField, len(e.Fields))}
	copy(out.Fields, e.Fields)
	for i := range out.Fields {
		if strings.EqualFold(out.Fields[i].Name, name) {
			out.Fields[i].Value = value
			return out
		}
	}
	return out
}

func (e *ASSEvent) clone() *ASSEvent {
	if e == nil {
		return nil
	}
	out := &ASSEvent{Fields: make([]ASSField, len(e.Fields))}
	copy(out.Fields, e.Fields)
	return out
}

func (m *ASSMetadata) clone() *ASSMetadata {
	if m == nil {
		return nil
	}
	out := &ASSMetadata{
		Header:      m.Header,
		EventFormat: m.EventFormat,
		Styles:      append([]string(nil), m.Styles...),
		Sections:    make([]ASSSection, len(m.Sections)),
	}
	for i, section := range m.Sections {
		out.Sections[i] = ASSSection{
			Name:  section.Name,
			Lines: append([]string(nil), section.Lines...),
		}
	}
	return out
}

// eventFormat returns the events Format line, falling back to any [Events]
// section preserved by a source without dialogue lines.
func (m *ASSMetadata) eventFormat() string {
	if m == nil {
		return defaultASSEventFormat
	}
	if m.EventFormat != "" {
		return m.EventFormat
	}
	for _, section := range m.Sections {
		if !strings.EqualFold(section.Name, "Events") {
			continue
		}
		for _, line := range section.Lines {
			trimmed := strings.TrimSpace(line)
			if strings.HasPrefix(trimmed, "Format:") {
				return strings.TrimSpace(strings.TrimPrefix(trimmed, "Format:"))
			}
		}
	}
	return defaultASSEventFormat
}

func (m *ASSMetadata) hasSection(name string) bool {
	if m == nil {
		return false
	}
	for _, section := range m.Sections {
		if strings.EqualFold(section.Name, name) {
			return true
		}
	}
	return false
}

func (m *ASSMetadata) isStyleSection(name string) bool {
	return strings.EqualFold(name, "V4+ Styles") || strings.EqualFold(name, "V4 Styles")
}

func (m *ASSMetadata) sectionBytes(name string) []byte {
	if m == nil {
		return nil
	}
	for _, section := range m.Sections {
		if !strings.EqualFold(section.Name, name) {
			continue
		}
		var buf bytes.Buffer
		fmt.Fprintf(&buf, "[%s]\n", section.Name)
		// Drop trailing blank lines: the encoder adds exactly one separator.
		lines := section.Lines
		for len(lines) > 0 && strings.TrimSpace(lines[len(lines)-1]) == "" {
			lines = lines[:len(lines)-1]
		}
		for _, line := range lines {
			buf.WriteString(line)
			buf.WriteByte('\n')
		}
		buf.WriteByte('\n')
		return buf.Bytes()
	}
	return nil
}

const defaultASSStyle = "Default"

const defaultASSStyleTable = "Format: Name, Fontname, Fontsize, PrimaryColour, SecondaryColour, OutlineColour, BackColour, Bold, Italic, Underline, StrikeOut, ScaleX, ScaleY, Spacing, Angle, BorderStyle, Outline, Shadow, Alignment, MarginL, MarginR, MarginV, Encoding\n" +
	"Style: Default,Arial,20,&H00FFFFFF,&H000000FF,&H00000000,&H00000000,0,0,0,0,100,100,0,0,1,2,2,2,10,10,10,1\n\n"

const defaultASSScriptInfo = "; Script generated by subgo\nScriptType: v4.00+\nPlayResX: 384\nPlayResY: 288\n\n"

const defaultASSEventFormat = "Layer, Start, End, Style, Name, MarginL, MarginR, MarginV, Effect, Text"

// assFormat implements the ASS/SSA subtitle format.
type assFormat struct{}

func (assFormat) Name() string { return "ass" }

func (assFormat) Extensions() []string { return []string{".ass", ".ssa"} }

func (assFormat) Decode(r io.Reader) (Subtitle, error) {
	scanner := bufio.NewScanner(r)
	var events []Event

	meta := &ASSMetadata{}
	var current *ASSSection
	sawSection := false
	inEvents := false
	var formatFields []string

	for scanner.Scan() {
		line := scanner.Text()
		if strings.HasPrefix(line, "\uFEFF") {
			meta.Header = "\uFEFF"
			line = strings.TrimPrefix(line, "\uFEFF")
		}
		trimmed := strings.TrimSpace(line)

		// Section headers
		if strings.HasPrefix(trimmed, "[") && strings.HasSuffix(trimmed, "]") {
			section := trimmed[1 : len(trimmed)-1]
			sawSection = true
			inEvents = strings.EqualFold(section, "events")
			current = nil
			if inEvents {
				continue
			}
			meta.Sections = append(meta.Sections, ASSSection{Name: section})
			current = &meta.Sections[len(meta.Sections)-1]
			continue
		}

		if !sawSection {
			continue
		}

		if !inEvents {
			if current != nil {
				current.Lines = append(current.Lines, line)
			}
			continue
		}

		if trimmed == "" || strings.HasPrefix(trimmed, ";") {
			continue
		}

		// Parse Format line to know field order
		if strings.HasPrefix(trimmed, "Format:") {
			formatFields = parseASSFields(strings.TrimPrefix(trimmed, "Format:"))
			meta.EventFormat = strings.TrimSpace(strings.TrimPrefix(trimmed, "Format:"))
			continue
		}

		// Parse Dialogue lines
		if strings.HasPrefix(trimmed, "Dialogue:") {
			event, err := parseASSDialogue(strings.TrimPrefix(trimmed, "Dialogue:"), formatFields)
			if err != nil {
				// Skip malformed lines instead of failing
				continue
			}
			events = append(events, event)
		}
	}

	if err := scanner.Err(); err != nil {
		return Subtitle{}, err
	}

	if !sawSection && meta.Header == "" {
		return Subtitle{Events: events}, nil
	}
	for _, style := range declaredASSStyles(meta) {
		if !containsString(meta.Styles, style) {
			meta.Styles = append(meta.Styles, style)
		}
	}
	return Subtitle{Events: events, ASS: meta}, nil
}

func declaredASSStyles(meta *ASSMetadata) []string {
	var styles []string
	for _, section := range meta.Sections {
		if !meta.isStyleSection(section.Name) {
			continue
		}
		var fieldNames []string
		for _, line := range section.Lines {
			trimmed := strings.TrimSpace(line)
			switch {
			case strings.HasPrefix(trimmed, "Format:"):
				fieldNames = parseASSFields(strings.TrimPrefix(trimmed, "Format:"))
			case strings.HasPrefix(trimmed, "Style:"):
				if len(fieldNames) == 0 {
					// Without a Format line, the first style field is the name.
					style := strings.TrimSpace(strings.SplitN(
						strings.TrimPrefix(trimmed, "Style:"), ",", 2)[0])
					if style != "" && !containsString(styles, style) {
						styles = append(styles, style)
					}
					continue
				}
				values := strings.SplitN(strings.TrimPrefix(trimmed, "Style:"), ",", len(fieldNames))
				for i, name := range fieldNames {
					if name == "name" && i < len(values) {
						style := strings.TrimSpace(values[i])
						if style != "" && !containsString(styles, style) {
							styles = append(styles, style)
						}
					}
				}
			}
		}
	}
	return styles
}

func containsString(values []string, value string) bool {
	for _, v := range values {
		if v == value {
			return true
		}
	}
	return false
}

func (assFormat) Encode(w io.Writer, s Subtitle) error {
	buf := &bytes.Buffer{}

	if s.ASS != nil {
		buf.WriteString(s.ASS.Header)
		for _, section := range s.ASS.Sections {
			if strings.EqualFold(section.Name, "Events") {
				// Events are regenerated below.
				continue
			}
			buf.Write(s.ASS.sectionBytes(section.Name))
		}
	}
	if !s.ASS.hasSection("Script Info") {
		buf.WriteString("[Script Info]\n")
		buf.WriteString(defaultASSScriptInfo)
	}
	if !s.ASS.hasSection("V4+ Styles") && !s.ASS.hasSection("V4 Styles") {
		buf.WriteString("[V4+ Styles]\n")
		buf.WriteString(defaultASSStyleTable)
	}

	buf.WriteString("[Events]\n")
	eventFormat := s.ASS.eventFormat()
	fmt.Fprintf(buf, "Format: %s\n", eventFormat)

	eventFields := parseASSFields(eventFormat)
	for _, e := range s.Events {
		assEvent := e.ASS
		if assEvent == nil {
			assEvent = defaultASSEvent(e)
		}
		fmt.Fprintf(buf, "Dialogue: %s\n", encodeASSFields(assEvent, eventFields, e))
	}

	_, err := w.Write(buf.Bytes())
	return err
}

// defaultASSEvent builds v4+ dialogue fields for an event without ASS metadata.
func defaultASSEvent(e Event) *ASSEvent {
	text := strings.ReplaceAll(e.Text, "\n", "\\N")
	return &ASSEvent{Fields: []ASSField{
		{Name: "layer", Value: "0"},
		{Name: "start", Value: ""},
		{Name: "end", Value: ""},
		{Name: "style", Value: defaultASSStyle},
		{Name: "name", Value: ""},
		{Name: "marginl", Value: "0"},
		{Name: "marginr", Value: "0"},
		{Name: "marginv", Value: "0"},
		{Name: "effect", Value: ""},
		{Name: "text", Value: text},
	}}
}

// encodeASSFields renders a dialogue line in eventFields order. Start and End
// always come from the event timing; the text field comes from the event text.
func encodeASSFields(e *ASSEvent, eventFields []string, event Event) string {
	fields := make([]string, len(eventFields))
	for i, name := range eventFields {
		value, ok := e.Value(name)
		switch {
		case !ok:
			value = ""
		case strings.EqualFold(name, "start"):
			value = formatASSTimestamp(event.Start)
		case strings.EqualFold(name, "end"):
			value = formatASSTimestamp(event.End)
		case strings.EqualFold(name, "text"):
			value = strings.ReplaceAll(event.Text, "\n", "\\N")
		}
		fields[i] = value
	}
	return strings.Join(fields, ",")
}

// parseASSFields parses the Format line fields.
func parseASSFields(s string) []string {
	parts := strings.Split(s, ",")
	fields := make([]string, len(parts))
	for i, p := range parts {
		fields[i] = strings.ToLower(strings.TrimSpace(p))
	}
	return fields
}

// parseASSDialogue parses a Dialogue line using the format fields.
func parseASSDialogue(s string, formatFields []string) (Event, error) {
	if len(formatFields) == 0 {
		formatFields = parseASSFields(defaultASSEventFormat)
	}
	// ASS dialogue has comma-separated fields, but the last field (Text) can contain commas
	// So we split by comma but limit to len(formatFields) parts
	parts := strings.SplitN(s, ",", len(formatFields))
	if len(parts) < len(formatFields) {
		return Event{}, fmt.Errorf("not enough fields in dialogue line")
	}

	// Build a map of field name -> value
	fieldMap := make(map[string]string)
	for i, field := range formatFields {
		fieldMap[field] = strings.TrimSpace(parts[i])
	}

	// Parse start time
	startStr, ok := fieldMap["start"]
	if !ok {
		return Event{}, fmt.Errorf("missing Start field")
	}
	start, err := parseASSTimestamp(startStr)
	if err != nil {
		return Event{}, err
	}

	// Parse end time
	endStr, ok := fieldMap["end"]
	if !ok {
		return Event{}, fmt.Errorf("missing End field")
	}
	end, err := parseASSTimestamp(endStr)
	if err != nil {
		return Event{}, err
	}

	// Preserve every field in order.
	assEvent := &ASSEvent{Fields: make([]ASSField, 0, len(formatFields))}
	for i, name := range formatFields {
		assEvent.Fields = append(assEvent.Fields, ASSField{
			Name:  name,
			Value: strings.TrimSpace(parts[i]),
		})
	}

	// Get text
	text := fieldMap["text"]
	// Convert \N and \n to actual newlines
	text = strings.ReplaceAll(text, "\\N", "\n")
	text = strings.ReplaceAll(text, "\\n", "\n")

	return Event{
		Start: start,
		End:   end,
		Text:  text,
		ASS:   assEvent,
	}, nil
}

// parseASSTimestamp parses ASS timestamp format: H:MM:SS.cc (centiseconds).
func parseASSTimestamp(s string) (time.Duration, error) {
	s = strings.TrimSpace(s)

	// Split by dot for centiseconds
	parts := strings.Split(s, ".")
	if len(parts) != 2 {
		return 0, fmt.Errorf("invalid ASS timestamp: %q", s)
	}

	timePart := parts[0]
	csPart := parts[1]

	// Parse time part H:MM:SS
	timeFields := strings.Split(timePart, ":")
	if len(timeFields) != 3 {
		return 0, fmt.Errorf("invalid ASS timestamp: %q", s)
	}

	h, err := strconv.Atoi(timeFields[0])
	if err != nil {
		return 0, err
	}
	m, err := strconv.Atoi(timeFields[1])
	if err != nil {
		return 0, err
	}
	sec, err := strconv.Atoi(timeFields[2])
	if err != nil {
		return 0, err
	}
	cs, err := strconv.Atoi(csPart)
	if err != nil {
		return 0, err
	}

	d := time.Hour*time.Duration(h) +
		time.Minute*time.Duration(m) +
		time.Second*time.Duration(sec) +
		time.Millisecond*time.Duration(cs*10) // centiseconds to milliseconds

	return d, nil
}

// formatASSTimestamp formats a duration as ASS timestamp: H:MM:SS.cc (centiseconds).
func formatASSTimestamp(d time.Duration) string {
	if d < 0 {
		d = 0
	}
	h := int(d / time.Hour)
	d -= time.Duration(h) * time.Hour
	m := int(d / time.Minute)
	d -= time.Duration(m) * time.Minute
	sec := int(d / time.Second)
	d -= time.Duration(sec) * time.Second
	cs := int(d/time.Millisecond) / 10 // milliseconds to centiseconds

	return fmt.Sprintf("%d:%02d:%02d.%02d", h, m, sec, cs)
}
